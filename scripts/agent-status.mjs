#!/usr/bin/env node
// Keep one GitHub issue ("Agent status", label `agent-status`) up to date with the real state of the
// automation: the backlog issues by label, open agent PRs with their CI state, the last merges, and
// whether main is green. Reads only GitHub's own data; no AI, no cost, nothing to configure.
//
//   node scripts/agent-status.mjs           print the report
//   node scripts/agent-status.mjs --write   create or update the status issue
import { execFileSync } from 'node:child_process';

const REPO = process.env.GITHUB_REPOSITORY || 'lonerkd/MisfitsCavernB';
const write = process.argv.includes('--write');

const gh = (args, input) => execFileSync('gh', args, { encoding: 'utf8', input, stdio: ['pipe', 'pipe', 'pipe'] });
const json = (args) => JSON.parse(gh(args) || '[]');

const ciState = (rollup) => {
  const checks = rollup ?? [];
  if (checks.some((c) => ['FAILURE', 'CANCELLED', 'TIMED_OUT'].includes(c.conclusion))) return 'failing';
  if (checks.some((c) => c.status && c.status !== 'COMPLETED')) return 'running';
  return checks.length ? 'passing' : 'no checks';
};
const ago = (iso) => {
  const h = Math.round((Date.now() - new Date(iso).getTime()) / 36e5);
  return h < 48 ? `${h}h ago` : `${Math.round(h / 24)}d ago`;
};

function report() {
  const issues = json(['issue', 'list', '--repo', REPO, '--state', 'open', '--limit', '500', '--json', 'number,title,labels']);
  const has = (i, name) => i.labels.some((l) => l.name === name);
  const backlog = issues.filter((i) => has(i, 'backlog'));
  const ready = issues.filter((i) => has(i, 'agent-ready'));
  const working = issues.filter((i) => has(i, 'agent-working'));
  const needsOwner = backlog.filter((i) => has(i, 'needs-owner'));
  const untouched = backlog.filter((i) => !has(i, 'agent-ready') && !has(i, 'agent-working') && !has(i, 'needs-owner'));

  const prs = json(['pr', 'list', '--repo', REPO, '--state', 'open', '--limit', '100', '--json', 'number,title,headRefName,isDraft,updatedAt,statusCheckRollup']);
  const agentPrs = prs.filter((p) => /^(claude|copilot|agent)\//.test(p.headRefName));
  const merged = json(['pr', 'list', '--repo', REPO, '--state', 'merged', '--limit', '5', '--json', 'number,title,mergedAt']);

  let main = 'unknown';
  try {
    const runs = json(['run', 'list', '--repo', REPO, '--branch', 'main', '--workflow', 'ci.yml', '--limit', '1', '--json', 'conclusion,status,createdAt,url']);
    if (runs[0]) main = `${runs[0].conclusion || runs[0].status} (${ago(runs[0].createdAt)})`;
  } catch { /* the workflow may not have run yet */ }

  const row = (i) => `- #${i.number} ${i.title}`;
  const lines = [
    `Generated by \`scripts/agent-status.mjs\` at ${new Date().toISOString()}. Do not edit; the next run replaces this text.`,
    '',
    `**main CI:** ${main}`,
    '',
    '### Backlog issues',
    `| State | Count |`,
    `| --- | --- |`,
    `| open backlog issues | ${backlog.length} |`,
    `| waiting on the owner (\`needs-owner\`) | ${needsOwner.length} |`,
    `| not yet read by the owner | ${untouched.length} |`,
    `| ready for an agent (\`agent-ready\`) | ${ready.length} |`,
    `| an agent is on it (\`agent-working\`) | ${working.length} |`,
    '',
    ready.length ? `**Ready for an agent**\n${ready.map(row).join('\n')}` : '_Nothing is labelled `agent-ready`. Read an issue, then add the label to hand it to an agent._',
    '',
    `### Agent pull requests (${agentPrs.length})`,
    agentPrs.length ? agentPrs.map((p) => `- #${p.number} ${p.title} — CI ${ciState(p.statusCheckRollup)}${p.isDraft ? ', draft' : ''}, updated ${ago(p.updatedAt)}`).join('\n') : '_None open._',
    '',
    '### Last merged',
    merged.map((p) => `- #${p.number} ${p.title} (${ago(p.mergedAt)})`).join('\n') || '_None._',
  ];
  return lines.join('\n');
}

function main() {
  const body = report();
  if (!write) { console.log(body); return; }
  const open = json(['issue', 'list', '--repo', REPO, '--state', 'open', '--label', 'agent-status', '--json', 'number']);
  if (open[0]) {
    gh(['issue', 'edit', String(open[0].number), '--repo', REPO, '--body-file', '-'], body);
    console.log(`updated issue #${open[0].number}`);
  } else {
    const url = gh(['issue', 'create', '--repo', REPO, '--title', 'Agent status', '--label', 'agent-status', '--body-file', '-'], body).trim();
    console.log(`created ${url}`);
  }
}

main();
